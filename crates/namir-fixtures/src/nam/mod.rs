/// Builds the flat weight array in the order `a2_infer::run` (and any real A2-shape `.nam`
/// reader) consumes it, derived directly from the upstream weight-consumption walk and
/// cross-checked against `a2_fast.cpp`'s own independent restatement of the same order
/// (`A2FastModel::_load_weights`, ~186-266 — its doc comment there states the identical order
/// this comment derives independently from `model.cpp`/`conv1d.cpp`/`dsp.cpp`).
///
/// `WaveNet::set_weights_` (`model.cpp:623-645`) reads, per layer array, `LayerArray::set_weights_`
/// (`model.cpp:525-531`): `_rechannel`, then each layer's `Layer::set_weights_`
/// (`model.cpp:135-164`) in turn, then `_head_rechannel`. Per layer (`Layer::set_weights_`'s
/// literal call order, matching its constructor's module order in `detail.h:44-53`): `_conv`
/// (dilated), `_input_mixin`, `_layer1x1` — `_head1x1` and every FiLM module are skipped, since
/// core A2 never activates them. After every layer array, a single trailing `head_scale` float is
/// read (`model.cpp:632`) — confirmed still present for A2: `WaveNet::set_weights_` reads it
/// unconditionally after the layer-array loop and the (absent, for A2) `_post_stack_head`, with no
/// architecture-specific branch, and `A2FastModel::_load_weights` reads the same trailing float
/// itself (`a2_fast.cpp:268-269`, "Matches `WaveNet::set_weights_`: the last value in the stream is
/// `head_scale`").
///
/// Each module's own weight order (`Conv1D::set_weights_`, `conv1d.cpp:10-54`;
/// `Conv1x1::set_weights_`, `dsp.cpp:363-398`): for each group (always 1 here), for each output
/// channel, for each input channel, for each kernel tap (tap innermost) — i.e. row-major
/// `[out][in][k]`, matching PyTorch's native `Conv1d.weight` flatten — then the module's bias
/// vector, if it has one. So, per layer array:
///
/// ```text
/// rechannel_w                     (channels * input_size; no bias)
/// for each layer:
///   dilated_conv_w, dilated_conv_b  (bottleneck * channels * kernel_size, then bottleneck)
///   mixin_w                         (bottleneck * condition_size; no bias)
///   layer1x1_w, layer1x1_b          (channels * bottleneck, then channels)
/// head_rechannel_w, head_rechannel_b
///                                  (head.out_channels * bottleneck * head.kernel_size,
///                                   then head.out_channels)
/// ```
/// ...then, after every layer array, a trailing `head_scale` float.
///
/// Constrained init, same reasoning as `build_weights`: every weight is uniform over `[-s, s]`
/// with `s = 1/sqrt(fan_in)`, the standard variance-preserving scale. Biases start at zero.
fn build_a2_weights(specs: &[A2LayerArrayConfig], rng: &mut impl Rng, head_scale: f32) -> Vec<f32> {
    let mut w = Vec::new();
    let push_uniform =
        |rng: &mut dyn rand::RngCore, out: &mut Vec<f32>, count: usize, scale: f32| {
            for _ in 0..count {
                out.push(rng.gen_range(-scale..scale));
            }
        };
    let push_zeros = |out: &mut Vec<f32>, count: usize| out.resize(out.len() + count, 0.0);

    for spec in specs {
        let s = 1.0 / (spec.input_size as f32).sqrt();
        push_uniform(rng, &mut w, spec.channels * spec.input_size, s);

        for &kernel_size in &spec.kernel_sizes {
            let s = 1.0 / ((spec.channels * kernel_size) as f32).sqrt();
            push_uniform(
                rng,
                &mut w,
                spec.bottleneck * spec.channels * kernel_size,
                s,
            );
            push_zeros(&mut w, spec.bottleneck);

            let s = 1.0 / (spec.condition_size as f32).sqrt();
            push_uniform(rng, &mut w, spec.bottleneck * spec.condition_size, s);

            let s = 1.0 / (spec.bottleneck as f32).sqrt();
            push_uniform(rng, &mut w, spec.channels * spec.bottleneck, s);
            push_zeros(&mut w, spec.channels);
        }

        let s = 1.0 / ((spec.bottleneck * spec.head.kernel_size) as f32).sqrt();
        push_uniform(
            rng,
            &mut w,
            spec.head.out_channels * spec.bottleneck * spec.head.kernel_size,
            s,
        );
        if spec.head.bias {
            push_zeros(&mut w, spec.head.out_channels);
        }
    }
    w.push(head_scale);
    w
}

fn measure_a2_output_rms(model: &A2Model, probe: &[f32]) -> f32 {
    let out = a2_infer::run(model, probe);
    let sum_sq: f64 = out.iter().map(|&v| (v as f64) * (v as f64)).sum();
    ((sum_sq / out.len() as f64).sqrt()) as f32
}

fn build_a2_model(shape: A2Shape, weights: Vec<f32>, head_scale: f32) -> A2Model {
    let layers = shape.layer_configs();
    A2Model {
        version: "0.5.5".to_string(),
        architecture: "WaveNet".to_string(),
        config: A2WaveNetConfig {
            layers,
            head_scale,
            head: None,
        },
        weights,
        sample_rate: SAMPLE_RATE,
        metadata: NamMetadata {
            name: format!("namir-fixtures generated {} WaveNet (A2)", shape.name()),
            modeled_by: "namir-fixtures".to_string(),
            gear_type: "amp".to_string(),
            tone_type: "clean".to_string(),
            description: "Seeded, constrained-init A2 WaveNet (D-19.1): not trained, tonal \
                realism is irrelevant, only architecture and weights matter for a parity test."
                .to_string(),
        },
    }
}

/// Generates a deterministic, RMS-calibrated `.nam` A2 fixture: same `(shape, seed)` always
/// produces byte-identical weights and output, on every platform. The A2 analogue of
/// [`generate`]; see that function's doc comment for the two-pass calibration shape this follows
/// unchanged, and for the cross-platform claim.
///
/// This is the shape that *demonstrated* the problem [`crate::detmath`] fixes. A2 inference is
/// LeakyReLU throughout — pure arithmetic, no libm — so the only transcendental anywhere in this
/// function was [`calibration_probe`]'s `sin`, and that alone was enough for M14's CI to
/// regenerate `a2_full.nam` with a different `head_scale` on all three runners. The committed
/// bytes now come back identical here; `namir-nam`'s `the_a2_golden_models_match_their_generator`
/// still compares that one value under a relative tolerance rather than byte for byte, which is
/// no longer necessary but is harmless.
pub fn generate_a2(shape: A2Shape, seed: u64) -> Result<A2Model, DegenerateFixtureError> {
    let specs = shape.layer_configs();
    let base_head_scale = 0.02f32;

    let mut rng = rand_pcg::Pcg64::seed_from_u64(seed);
    let weights = build_a2_weights(&specs, &mut rng, base_head_scale);
    let model = build_a2_model(shape, weights, base_head_scale);

    let probe = calibration_probe(seed);
    let measured_rms = measure_a2_output_rms(&model, &probe);
    if !measured_rms.is_finite() || measured_rms <= 1e-6 {
        return Err(DegenerateFixtureError { measured_rms });
    }

    let target_rms = 0.15f32;
    let calibrated_head_scale = base_head_scale * (target_rms / measured_rms);
    let mut weights = model.weights;
    *weights.last_mut().expect("head_scale weight present") = calibrated_head_scale;
    let model = build_a2_model(shape, weights, calibrated_head_scale);

    let calibrated_rms = measure_a2_output_rms(&model, &probe);
    if !calibrated_rms.is_finite() || calibrated_rms <= 1e-4 || calibrated_rms >= 10.0 {
        return Err(DegenerateFixtureError {
            measured_rms: calibrated_rms,
        });
    }

    Ok(model)
}

/// Builds the flat weight array in the order `lstm_infer::run` (and `namir-nam`'s `lstm.rs`)
/// consume it: per layer `[W, b, h0, c0]` (layer 0's `W` has `cell_input_size == input_size`,
/// every later layer's has `cell_input_size == hidden_size`), then `head_weight`, `head_bias` —
/// no trailing scalar, unlike WaveNet's `head_scale`.
///
/// Constrained init, same reasoning as `build_weights`: every `W`/`head_weight` entry is uniform
/// over `[-s, s]` with `s = 1/sqrt(fan_in)`. Biases (`b`, `head_bias`) start at zero. `h0`/`c0`
/// (the *learned* initial hidden/cell state — see `namir-nam`'s `lstm.rs` doc comment) get a
/// small uniform init of their own (`s = 0.1`, not fan-in-scaled): a real export's initial state
/// isn't zero, but there's no fan-in to scale it by either, and it isn't the calibration knob —
/// `generate_lstm`'s calibration pass rescales the head instead, since (unlike gate weights) the
/// head's output is exactly linear in its own weights (see `generate_lstm`'s doc comment).
fn build_lstm_weights(cfg: &LstmConfig, rng: &mut impl Rng) -> Vec<f32> {
    let mut w = Vec::new();
    let push_uniform =
        |rng: &mut dyn rand::RngCore, out: &mut Vec<f32>, count: usize, scale: f32| {
            for _ in 0..count {
                out.push(rng.gen_range(-scale..scale));
            }
        };
    let push_zeros = |out: &mut Vec<f32>, count: usize| out.resize(out.len() + count, 0.0);

    for i in 0..cfg.num_layers {
        let cell_input_size = if i == 0 {
            cfg.input_size
        } else {
            cfg.hidden_size
        };
        let rows = 4 * cfg.hidden_size;
        let cols = cell_input_size + cfg.hidden_size;
        let s = 1.0 / (cols as f32).sqrt();
        push_uniform(rng, &mut w, rows * cols, s); // W
        push_zeros(&mut w, rows); // b
        push_uniform(rng, &mut w, cfg.hidden_size, 0.1); // h0
        push_uniform(rng, &mut w, cfg.hidden_size, 0.1); // c0
    }

    let s = 1.0 / (cfg.hidden_size as f32).sqrt();
    push_uniform(rng, &mut w, cfg.out_channels * cfg.hidden_size, s); // head_weight
    push_zeros(&mut w, cfg.out_channels); // head_bias
    w
}

fn measure_lstm_output_rms(model: &LstmModel, probe: &[f32]) -> f32 {
    let out = lstm_infer::run(model, probe);
    let sum_sq: f64 = out.iter().map(|&v| (v as f64) * (v as f64)).sum();
    ((sum_sq / out.len() as f64).sqrt()) as f32
}

fn build_lstm_model(shape: LstmShape, weights: Vec<f32>) -> LstmModel {
    LstmModel {
        version: "0.5.5".to_string(),
        architecture: "LSTM".to_string(),
        config: shape.config(),
        weights,
        sample_rate: SAMPLE_RATE,
        metadata: NamMetadata {
            name: format!("namir-fixtures generated {} LSTM", shape.name()),
            modeled_by: "namir-fixtures".to_string(),
            gear_type: "amp".to_string(),
            tone_type: "clean".to_string(),
            description: "Seeded, constrained-init LSTM (D-19.1): not trained, tonal realism is \
                irrelevant, only architecture and weights matter for a parity test."
                .to_string(),
        },
    }
}

/// Generates a deterministic, RMS-calibrated `.nam` LSTM fixture: same `(shape, seed)` always
/// produces byte-identical weights and output, on every platform — the LSTM counterpart of
/// [`generate`]; see that function's doc comment for the two-pass shape this follows and for what
/// "on every platform" cost. This architecture reaches the platform libm twice over (`tanh` *and*
/// the sigmoid's `exp`), and its calibration scales the whole head tail rather than one float, so
/// a libm difference used to land in several weights rather than one.
///
/// The one structural difference from `generate`: WaveNet has a single trailing `head_scale`
/// float to rescale for calibration; LSTM has no such scalar (see `build_lstm_weights`'s doc
/// comment), so this rescales the flat weight array's *tail* — `head_weight` and `head_bias`
/// together, the last `out_channels * hidden_size + out_channels` floats — by a factor `k`
/// instead. That is exactly equivalent to WaveNet's single-float rescale, not an approximation:
/// the head is the last stage applied (`output = head_weight @ h_last + head_bias`) and nothing
/// upstream of it (the layer stack, `h_last` itself) depends on the head's own weights, so
/// scaling both `head_weight` and `head_bias` by `k` scales `output` by exactly `k`.
pub fn generate_lstm(shape: LstmShape, seed: u64) -> Result<LstmModel, DegenerateFixtureError> {
    let cfg = shape.config();

    let mut rng = rand_pcg::Pcg64::seed_from_u64(seed);
    let weights = build_lstm_weights(&cfg, &mut rng);
    let model = build_lstm_model(shape, weights);

    let probe = calibration_probe(seed);
    let measured_rms = measure_lstm_output_rms(&model, &probe);
    if !measured_rms.is_finite() || measured_rms <= 1e-6 {
        return Err(DegenerateFixtureError { measured_rms });
    }

    let target_rms = 0.15f32;
    let k = target_rms / measured_rms;
    let head_len = cfg.out_channels * cfg.hidden_size + cfg.out_channels;
    let mut weights = model.weights;
    let tail_start = weights
        .len()
        .checked_sub(head_len)
        .expect("weights always at least as long as the head, by construction");
    for w in &mut weights[tail_start..] {
        *w *= k;
    }
    let model = build_lstm_model(shape, weights);

    let calibrated_rms = measure_lstm_output_rms(&model, &probe);
    if !calibrated_rms.is_finite() || calibrated_rms <= 1e-4 || calibrated_rms >= 10.0 {
        return Err(DegenerateFixtureError {
            measured_rms: calibrated_rms,
        });
    }

    Ok(model)
}

