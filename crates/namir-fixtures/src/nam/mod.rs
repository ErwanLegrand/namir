// (`C:\namref`), specifically `NAM/wavenet/model.cpp`, `NAM/conv1d.cpp`, `NAM/dsp.cpp`,
// `NAM/wavenet/detail.h` and `NAM/wavenet/a2_fast.h`/`a2_fast.cpp`. This section is written
// independently of `crates/namir-nam`'s own A2 work (R-9, `docs/02-architecture.md` §22) — see
// this module's own doc comment and the milestone task that produced it for why that independence
// matters; nothing below was read from or cross-checked against `namir-nam`.

/// One layer's activation config inside an A2 layer array's `activation` array — this crate's
/// mirror of the real `.nam` schema's per-layer activation object (`a2_fast.cpp`'s detector,
/// `is_a2_shape`, ~825-835: `{"type": "LeakyReLU", "negative_slope": <f32>}`). Core A2 always uses
/// `negative_slope: 0.01` (`a2_fast.h`'s `kLeakySlope`), but the field is a real JSON knob —
/// `activations.cpp` confirms every activation parameter comes from config, never the weight
/// stream — so it's carried here rather than hard-coded past the generator boundary.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct A2ActivationConfig {
    /// Always `"LeakyReLU"` for fixtures generated by this module.
    #[serde(rename = "type")]
    pub kind: String,
    /// LeakyReLU's negative-slope coefficient; `0.01` for real "A2 standard"/"A2 nano" models.
    pub negative_slope: f32,
}

/// An A2 layer array's `layer1x1` sub-config — present and `active` on every layer of every
/// core-A2 shape (`a2_fast.cpp`'s detector requires it: ~866-873). `namir-fixtures` never emits
/// `head1x1`, `condition_dsp`, `gating_mode`, or `slimmable` fields at all (out of this module's
/// scope): omitting a mirror type for each of those leaves the field entirely absent from the
/// serialized JSON, which is exactly what the strict A2 detector requires for those particular
/// fields (`is_a2_shape`, `a2_fast.cpp:758-909` — each is only rejected when *present* and
/// non-trivial, so a config that never emits it still matches).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct A2Layer1x1Config {
    /// Always `true` for fixtures generated by this module — `layer1x1` inactive is a different,
    /// non-A2 WaveNet shape this crate does not generate (and would require `bottleneck ==
    /// channels`, `detail.h:60-65`).
    pub active: bool,
    /// Always `1` — core A2 never groups this convolution.
    pub groups: usize,
}

/// An A2 layer array's nested `head` sub-config: a genuine k-tap, dilated causal `Conv1D` (unlike
/// [`LayerArrayConfig`]'s implicit 1x1 head rechannel), matching `LayerArray`'s `_head_rechannel`
/// member (`detail.h:350-351`) and its construction (`model.cpp:380-384`: built directly from
/// `head_size`/`head_kernel_size`/`head_bias`/`head_dilation`, with its input width —
/// `_head_output_size` — equal to `bottleneck` since core A2 never activates `head1x1`).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct A2HeadRechannelConfig {
    /// Output channel count; `1` for both real A2 shapes (the detector requires exactly this).
    pub out_channels: usize,
    /// Convolution kernel width; `16` for both real A2 shapes (`kHeadKernelSize`, `a2_fast.h:33`).
    pub kernel_size: usize,
    /// Dilation factor; `1` for both real A2 shapes.
    pub head_dilation: usize,
    /// Whether this convolution applies a bias term; always `true` for fixtures generated by this
    /// module (matches both real A2 shapes — the detector requires it: `a2_fast.cpp:885`).
    pub bias: bool,
}

/// One A2 layer array's hyperparameters — the A2 analogue of [`LayerArrayConfig`], structurally
/// different rather than a superset: A2 has a per-layer `kernel_sizes`/`dilations` pair (not one
/// shared `kernel_size`), an internal `bottleneck` width distinct from `channels` (`detail.h`'s
/// `Layer` constructor, ~44-53), a per-layer `activation` array rather than one shared activation
/// name, an explicit `layer1x1` sub-config, and a real convolutional nested `head` rather than an
/// implicit 1x1. Field names mirror the real `.nam` A2 schema as read by `is_a2_shape`
/// (`a2_fast.cpp:758-909`).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct A2LayerArrayConfig {
    /// Number of input channels into this layer array; always `1` (raw mono signal) for fixtures
    /// generated by this module.
    pub input_size: usize,
    /// Number of conditioning channels; always `1`, and always fed the model's original raw
    /// input at every layer (see [`a2_infer::run`]'s doc comment on the two-signal handoff — same
    /// convention `infer.rs` already documents for A1, confirmed unchanged for A2 by
    /// `WaveNet::process`, `model.cpp:744-772`).
    pub condition_size: usize,
    /// Number of channels each layer's residual trunk carries (the `layer1x1` output width and
    /// the array's `_rechannel` output width).
    pub channels: usize,
    /// Number of channels the dilated conv / input mixin / activation operate at internally, per
    /// layer (`Layer`'s `_bottleneck`, `detail.h:45-53`). Equal to `channels` for both real A2
    /// shapes (the detector requires it: `a2_fast.cpp:798-803`) but deliberately *not* equal for
    /// [`A2Shape::BottleneckProbe`] — see that variant's doc comment.
    pub bottleneck: usize,
    /// Per-layer convolution kernel widths, one entry per layer.
    pub kernel_sizes: Vec<usize>,
    /// Per-layer dilation factors, one entry per layer.
    pub dilations: Vec<usize>,
    /// Per-layer activation config, one entry per layer; fixtures generated by this module always
    /// use `LeakyReLU`.
    pub activation: Vec<A2ActivationConfig>,
    /// The post-activation projection back to `channels` width feeding the residual connection
    /// (`detail.h`'s `_layer1x1`); always active for fixtures generated by this module.
    pub layer1x1: A2Layer1x1Config,
    /// The layer array's own dilated-conv head rechannel, applied once after all layers'
    /// activated outputs are summed.
    pub head: A2HeadRechannelConfig,
}

/// An A2 model's top-level configuration — the same shape as [`WaveNetConfig`] (`layers` +
/// `head_scale` + a `head` field that's always `null`/absent for both), just parameterized over
/// [`A2LayerArrayConfig`] instead of [`LayerArrayConfig`]. `namir-fixtures` only ever generates a
/// single layer array (core A2's own constraint — `a2_fast.cpp:760-763` rejects anything else), so
/// `layers` always has length 1, but the field stays a `Vec` — same reasoning as
/// [`WaveNetConfig::layers`] — rather than a single struct, so [`a2_infer::run`]'s array-chaining
/// loop isn't a special case for the one array it's ever actually given.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct A2WaveNetConfig {
    /// The model's layer-array stack, in evaluation order; always length 1 for fixtures generated
    /// by this module.
    pub layers: Vec<A2LayerArrayConfig>,
    /// Output scaling applied after the (nested, per-array) head; the value `generate_a2`'s
    /// calibration pass rescales.
    pub head_scale: f32,
    /// The model's *top-level*, post-stack head (`WaveNet::_post_stack_head`) — distinct from
    /// each layer array's own nested `head` above. Always `None`/absent: `is_a2_shape` requires
    /// this be null (`a2_fast.cpp:766-768`).
    pub head: Option<serde_json::Value>,
}

